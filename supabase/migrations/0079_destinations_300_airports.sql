-- ── 3) 공항 표 ──────────────────────────────────────────────────────────────
create table if not exists public.airports (
  iata         text primary key check (iata ~ '^[A-Z]{3}$'),
  country_code char(2) not null,
  -- 공항 이름·그 공항이 있는 도시 이름: { "ko": "...", "en": "...", "ja": "...", "zh-TW": "..." }
  name         jsonb not null,
  city         jsonb not null,
  lat          double precision not null,
  lng          double precision not null,
  timezone     text not null,
  created_at   timestamptz not null default now()
);

create table if not exists public.destination_airports (
  destination_id uuid not null references public.destinations(id) on delete cascade,
  iata           text not null references public.airports(iata) on delete cascade,
  is_primary     boolean not null default false,
  note           text,
  primary key (destination_id, iata)
);
create unique index if not exists destination_airports_one_primary on public.destination_airports (destination_id) where is_primary;
create index if not exists destination_airports_iata_idx on public.destination_airports (iata);

alter table public.airports enable row level security;
alter table public.destination_airports enable row level security;
drop policy if exists "public read airports" on public.airports;
create policy "public read airports" on public.airports for select using (true);
drop policy if exists "public read destination airports" on public.destination_airports;
create policy "public read destination airports" on public.destination_airports for select using (true);
grant select on public.airports, public.destination_airports to anon, authenticated;

